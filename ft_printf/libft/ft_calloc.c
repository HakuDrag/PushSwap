#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*answer;

	if (nmemb == 0 || size == 0)
		return (malloc(1));
	if (nmemb > SIZE_MAX / size)
		return (NULL);
	answer = malloc(nmemb * size);
	if (!answer)
		return (NULL);
	ft_bzero(answer, nmemb * size);
	return (answer);
}
