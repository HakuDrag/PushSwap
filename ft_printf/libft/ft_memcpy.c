#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	size_t				i;
	const unsigned char	*source;
	unsigned char		*dst;

	i = 0;
	source = src;
	dst = dest;
	while (i < n)
	{
		dst[i] = source[i];
		i++;
	}
	return (dest);
}
