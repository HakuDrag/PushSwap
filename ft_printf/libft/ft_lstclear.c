#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*deleted;
	t_list	*next;

	if (!lst || !del)
		return ;
	deleted = *lst;
	while (deleted)
	{
		next = deleted->next;
		ft_lstdelone(deleted, del);
		deleted = next;
	}
	*lst = NULL;
}
