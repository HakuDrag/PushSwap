#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*pointer;

	if (!lst || !new)
		return ;
	if (!*lst)
	{
		*lst = new;
		return ;
	}
	pointer = *lst;
	while (pointer->next)
		pointer = pointer->next;
	pointer->next = new;
}
